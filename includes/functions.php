/**
 * External links used in the admin pages.
 *
 * @since 1.1.0
 * @author Monzur Alam
 *
 * @param string $key docs|support|review|github|video
 * @return string
 */
if (!function_exists('uts_link')) {
    function uts_link($key) {
        $links = array(
            'docs'    => 'https://wordpress.org/plugins/ultimate-3d-testimonial-slider/',
            'support' => 'https://wordpress.org/support/plugin/ultimate-3d-testimonial-slider/',
            'review'  => 'https://wordpress.org/support/plugin/ultimate-3d-testimonial-slider/reviews/#new-post',
            'github'  => 'https://github.com/monzuralam/ultimate-3d-testimonial-slider',
            // Getting Started tutorial video (empty = "coming soon" placeholder).
            'video'   => 'https://youtu.be/KzOUthyMGew',
        );

        return isset($links[$key]) ? $links[$key] : '';
    }
}

/**
 * Register a compiled entry from the build directory.
 *
 * Reads the dependencies and version hash generated by @wordpress/scripts
 * and registers a script and a style under the same handle.
 *
 * @since 1.1.0
 * @author Monzur Alam
 *
 * @param string $handle Script/style handle.
 * @param string $entry  Entry name in the build directory (e.g. 'frontend').
 * @return bool Whether the entry was registered.
 */
if (!function_exists('uts_register_build')) {
    function uts_register_build($handle, $entry) {
        $asset_file = UTS_BUILD . '/' . $entry . '.asset.php';

        if (!file_exists($asset_file)) {
            return false;
        }

        $asset = require $asset_file;

        if (in_array('react-jsx-runtime', $asset['dependencies'], true)) {
            \UTS\Assets::register_jsx_runtime_fallback();
        }

        if (file_exists(UTS_BUILD . '/' . $entry . '.css')) {
            wp_register_style($handle, UTS_BUILD_URL . '/' . $entry . '.css', array(), $asset['version'], 'all');
            wp_style_add_data($handle, 'rtl', 'replace');
        }

        wp_register_script($handle, UTS_BUILD_URL . '/' . $entry . '.js', $asset['dependencies'], $asset['version'], true);

        return true;
    }
}

/**
 * YouTube video ID from a URL (watch, youtu.be, embed or shorts links).
 *
 * @since 1.1.0
 * @author Monzur Alam
 *
 * @param string $url YouTube URL.
 * @return string Video ID, or '' if the URL isn't a YouTube video.
 */
if (!function_exists('uts_youtube_id')) {
    function uts_youtube_id($url) {
        if (preg_match('~(?:youtube(?:-nocookie)?\.com/(?:watch\?(?:.*&)?v=|embed/|shorts/|live/)|youtu\.be/)([A-Za-z0-9_-]{11})~', (string) $url, $matches)) {
            return $matches[1];
        }

        return '';
    }
}

/**
 * Register the `uts` post type and `uts_category` taxonomy.
 *
 * Public API since 1.0.1, kept for back-compat: themes and snippets may
 * call it. The plugin itself registers them through UTS\CPT. Adds no hooks.
 *
 * @since 1.0.1
 * @author Monzur Alam
 */
if ( ! function_exists( 'uts_setup_post_type' ) ) {
	function uts_setup_post_type() {
		$cpt = new \UTS\CPT();
		$cpt->register_types();
	}
}

/**
 * Get the settings, merged over the defaults.
 *
 * Public API: themes and snippets may call it. Reads through UTS\Settings.
 *
 * @since 1.1.0
 * @author Monzur Alam
 *
 * @param string|null $key Optional setting key.
 * @return mixed All settings, or one value (null if the key is unknown).
 */
if ( ! function_exists( 'uts_get_settings' ) ) {
	function uts_get_settings( $key = null ) {
		return \UTS\Settings::get( $key );
	}
}

/**
 * Get a saved shortcode instance (`[uts id="5"]`).
 *
 * Public API: themes and snippets may call it. Returns the instance in any
 * status, so check `status` before using it on the frontend.
 *
 * @since 1.1.0
 * @author Monzur Alam
 *
 * @param int $id Instance ID.
 * @return array|null { id, title, settings, status, author_id, created_at, updated_at }, or null.
 */
if ( ! function_exists( 'uts_get_shortcode' ) ) {
	function uts_get_shortcode( $id ) {
		return \UTS\DB::get( $id );
	}
}

/**
 * Render the [uts] shortcode.
 *
 * Public API since 1.0.1, kept for back-compat: themes may call it directly,
 * e.g. echo uts_shortcode( array( 'type' => 'grid' ) ). Shares the instance
 * counter with the shortcode. Adds no hooks.
 *
 * @since 1.0.1
 * @author Monzur Alam
 *
 * @param array|string $atts Shortcode attributes.
 * @return string The HTML output.
 */
if ( ! function_exists( 'uts_shortcode' ) ) {
	function uts_shortcode( $atts ) {
		$shortcode = new \UTS\Shortcode();
		return $shortcode->render( $atts );
	}
}
