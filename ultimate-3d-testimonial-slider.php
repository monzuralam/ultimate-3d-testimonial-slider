/**
 * define constants
 */
define( 'UTS_VERSION', '1.0.1' );
define( 'UTS_FILE', __FILE__ );
define( 'UTS_PATH', dirname( UTS_FILE ) );
define( 'UTS_URL', plugins_url( '', UTS_FILE ) );
define( 'UTS_ASSETS', UTS_URL . '/assets' );
define( 'UTS_INCLUDES', UTS_PATH . '/includes' );
define( 'UTS_BUILD', UTS_PATH . '/build' );
define( 'UTS_BUILD_URL', UTS_URL . '/build' );

/**
 * Enqueue a compiled entry from the build directory.
 *
 * Reads the dependencies and version hash generated by @wordpress/scripts.
 *
 * @since 1.1.0
 * @author Monzur Alam
 *
 * @param string $handle Script/style handle.
 * @param string $entry  Entry name in the build directory (e.g. 'frontend').
 */
if (!function_exists('uts_enqueue_build')) {
    function uts_enqueue_build($handle, $entry) {
        $asset_file = UTS_BUILD . '/' . $entry . '.asset.php';

        if (!file_exists($asset_file)) {
            return;
        }

        $asset = require $asset_file;

        wp_enqueue_style($handle, UTS_BUILD_URL . '/' . $entry . '.css', array(), $asset['version'], 'all');
        wp_style_add_data($handle, 'rtl', 'replace');
        wp_enqueue_script($handle, UTS_BUILD_URL . '/' . $entry . '.js', $asset['dependencies'], $asset['version'], true);
    }
}

/**
 * Enqueue CSS & JS
 */
if (!function_exists('uts_assets')) {
    function uts_assets(){
        uts_enqueue_build('uts', 'frontend');
    }
    add_action('wp_enqueue_scripts', 'uts_assets');
}

/**
 * Admin Assets
 * @since 1.0.1
 * @author  Monzur Alam
 */
if (!function_exists('uts_admin_assets')) {
    function uts_admin_assets(){
        uts_enqueue_build('uts-admin', 'admin');
    }
    add_action('admin_enqueue_scripts', 'uts_admin_assets');
}

/**
 * Activate the plugin.
 */
function uts_active() { 
    // Trigger our function that registers the cutsom post type plugin.
    uts_setup_post_type(); 
    // Clear the permalinks after the post type has been registered.
    flush_rewrite_rules(); 
}
register_activation_hook( __FILE__, 'uts_active' );

/**
 * Deactivation hook.
 */
function uts_deactivate() {
    // Unregister the post type, so the rules are no longer in memory.
    unregister_post_type( 'uts' );
    // Clear the permalinks to remove our post type's rules from the database.
    flush_rewrite_rules();
}
register_deactivation_hook( __FILE__, 'uts_deactivate' );

